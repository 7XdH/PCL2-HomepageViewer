import fs from "node:fs";
import path from "node:path";

const root = path.join(process.cwd(), "assets", "pcl", "images");
const files = [];
const walk = dir => {
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (fs.statSync(file).isDirectory()) walk(file);
    else files.push(path.relative(root, file).replaceAll("\\", "/"));
  }
};
walk(root);
files.sort((a, b) => a.localeCompare(b));

const body = `// Generated by tools/generate-assets.mjs from PCL's Images folder.
// Maps PCL pack:// image paths to case-correct web asset URLs.
export const IMAGE_FILES = ${JSON.stringify(files, null, 2)};

export const IMAGE_MAP = Object.fromEntries(IMAGE_FILES.map(file => [file.toLowerCase(), file]));

export function resolvePclImage(relativePath) {
  const clean = String(relativePath ?? "").replaceAll("\\\\", "/").replace(/^\\/+/, "");
  if (/^(https?:|data:|blob:)/i.test(clean)) return clean;
  const hit = IMAGE_MAP[clean.toLowerCase()];
  if (!hit) return null;
  return "assets/pcl/images/" + hit.split("/").map(encodeURIComponent).join("/");
}
`;

fs.writeFileSync(path.join(process.cwd(), "js", "assets.js"), body, "utf8");
console.log(`Generated js/assets.js with ${files.length} image entries.`);
